#!/usr/bin/env node

import { execFileSync, spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { chmodSync, copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';

const ENV_FILE = '.env.local';

function fail(message) {
  console.error(`\nLocal DEV setup stopped: ${message}\n`);
  process.exit(1);
}

function run(command, args, options = {}) {
  console.log(`\n> ${command} ${args.join(' ')}`);
  return execFileSync(command, args, { encoding: 'utf8', stdio: 'inherit', ...options });
}

function parseEnv(text) {
  const result = {};
  for (const line of text.split(/\r?\n/)) {
    const match = line.match(/^([A-Z][A-Z0-9_]*)=(.*)$/);
    if (!match) continue;
    const [, key, rawValue] = match;
    try {
      result[key] = rawValue.startsWith('"') ? JSON.parse(rawValue) : rawValue;
    } catch {
      result[key] = rawValue.replace(/^"|"$/g, '');
    }
  }
  return result;
}

function readCurrentValue(name) {
  if (!existsSync(ENV_FILE)) return null;
  const match = readFileSync(ENV_FILE, 'utf8').match(new RegExp(`^${name}=(.*)$`, 'm'));
  return match?.[1]?.trim().replace(/^"|"$/g, '') || null;
}

if (spawnSync('docker', ['info'], { stdio: 'ignore' }).status !== 0) {
  fail('Docker Desktop is not installed or is not running. Start Docker Desktop and run npm run dev:setup again.');
}

// Start the isolated local Supabase stack. This never links to a cloud project.
run('npx', ['supabase', 'start']);

let statusOutput;
try {
  statusOutput = execFileSync('npx', ['supabase', 'status', '-o', 'env'], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
} catch {
  fail('Supabase started, but its local credentials could not be read. Run npx supabase status to diagnose it.');
}

const local = parseEnv(statusOutput);
for (const key of ['API_URL', 'ANON_KEY', 'SERVICE_ROLE_KEY']) {
  if (!local[key]) fail(`Supabase status did not return ${key}.`);
}

const currentUrl = readCurrentValue('NEXT_PUBLIC_SUPABASE_URL');
const previousEnvWasLocal = ['http://127.0.0.1:54321', 'http://localhost:54321'].includes(currentUrl || '');
const existingDemoPassword = previousEnvWasLocal ? readCurrentValue('DEMO_USER_PASSWORD') : null;

if (existsSync(ENV_FILE)) {
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  const backup = `.env.local.backup-${stamp}`;
  copyFileSync(ENV_FILE, backup);
  console.log(`Existing ${ENV_FILE} was preserved as ${backup}.`);
}

const demoPassword = existingDemoPassword || `MetroFit-${randomBytes(12).toString('base64url')}!`;
const env =
  `# Generated by npm run dev:setup. LOCAL DEV ONLY.\n` +
  `NEXT_PUBLIC_SUPABASE_URL=${local.API_URL}\n` +
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${local.ANON_KEY}\n` +
  `SUPABASE_SERVICE_ROLE_KEY=${local.SERVICE_ROLE_KEY}\n` +
  `NEXT_PUBLIC_APP_NAME="METRO Fit Team DEV"\n` +
  `NEXT_PUBLIC_DEFAULT_LOCALE=de\n` +
  `INITIAL_ADMIN_EMAIL=thorsten@demo.metro-fit-team.local\n` +
  `INITIAL_TEAM_NAME="METRO Marl Fitness Team DEV"\n` +
  `NEXT_PUBLIC_APP_URL=http://localhost:3000\n` +
  `NEXT_PUBLIC_VAPID_PUBLIC_KEY=\n` +
  `VAPID_PRIVATE_KEY=\n` +
  `SMTP_HOST=\nSMTP_PORT=465\nSMTP_SECURE=true\nSMTP_USER=\nSMTP_PASS=\nINVITE_EMAIL_FROM=\n` +
  `DEMO_USER_PASSWORD=${demoPassword}\n` +
  `ALLOW_REMOTE_DEV_SEED=false\n`;

writeFileSync(ENV_FILE, env, { mode: 0o600 });
chmodSync(ENV_FILE, 0o600);

if (currentUrl && !previousEnvWasLocal) {
  console.log('The previous environment pointed to a remote Supabase project; the active file now points only to local DEV.');
}

// Rebuild the local database from migrations, seed the exercise catalogue,
// then add disposable demo users and realistic app data.
run('npx', ['supabase', 'db', 'reset']);
run('npm', ['run', 'seed']);

console.log('\nLocal DEV is ready. Run npm run dev and open http://localhost:3000.');
console.log(`All demo users use this local-only password: ${demoPassword}`);
console.log('Recommended login: thorsten@demo.metro-fit-team.local');
